function buildDemoPublishedSlots(now: Date) {
  const slots: Array<{
    id: string;
    scheduled_at: string;
    duration_minutes: number;
    created_at: string;
    updated_at: string;
  }> = [];
  let n = 0;
  for (let d = 1; d <= 14; d++) {
    const day = new Date(now.getFullYear(), now.getMonth(), now.getDate() + d);
    const weekday = day.getDay();
    if (![2, 4, 6].includes(weekday)) continue;
    const hours = weekday === 6 ? [9, 10, 11] : [10, 11, 14, 15, 16];
    for (const h of hours) {
      n += 1;
      const at = new Date(day.getFullYear(), day.getMonth(), day.getDate(), h, 0, 0);
      slots.push({
        id: `slot_demo_${n}`,
        scheduled_at: at.toISOString(),
        duration_minutes: 60,
        created_at: now.toISOString(),
        updated_at: now.toISOString(),
      });
    }
  }
  return slots;
}
