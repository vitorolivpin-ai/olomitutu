function dueDate(day: number, comp = competence) {
  const [y, m] = comp.split("-").map(Number);
  const last = new Date(y, m, 0).getDate();
  const d = Math.min(day, last);
  return `${comp}-${String(d).padStart(2, "0")}`;
}

